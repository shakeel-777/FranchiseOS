import { useEffect, useState } from 'react';
import { ReportAPI } from '../../api/client';
import { useToast } from '../../context/ToastContext';
import { searchFilter, paginate, fmtDateTime } from '../../utils/format';
import DataTable from '../../components/DataTable';
import Modal from '../../components/Modal';
import Pagination from '../../components/Pagination';
import SearchBox from '../../components/SearchBox';

const TYPES = [
  ['sales', 'Sales Report'], ['inventory', 'Inventory Report'], ['expense', 'Expense Report'],
  ['compliance', 'Compliance Report'], ['performance', 'Performance Report'], ['custom', 'Custom Report'],
];
const EMPTY = { report_type: 'custom', title: '', notes: '' };

export default function Reports() {
  const toast = useToast();

  const [list, setList] = useState([]);
  const [loading, setLoading] = useState(true);
  const [query, setQuery] = useState('');
  const [page, setPage] = useState(1);
  const [modal, setModal] = useState(null); // null | 'new' | report
  const [form, setForm] = useState(EMPTY);
  const [saving, setSaving] = useState(false);

  async function load() {
    setLoading(true);
    try {
      const res = await ReportAPI.list();
      setList(res.results || res || []);
    } catch (err) {
      toast(err.message, 'error');
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => { load(); }, []); // eslint-disable-line react-hooks/exhaustive-deps

  const filtered = searchFilter(list, query, ['title']);
  const { slice, total } = paginate(filtered, page, 8);

  function openNew() { setForm(EMPTY); setModal('new'); }

  async function create() {
    setSaving(true);
    try {
      await ReportAPI.create(form);
      toast('Report generated', 'success');
      setModal(null);
      load();
    } catch (err) {
      toast(err.message, 'error');
    } finally {
      setSaving(false);
    }
  }

  async function remove(row) {
    if (!window.confirm(`Delete report "${row.title}"?`)) return;
    try { await ReportAPI.remove(row.id); toast('Report deleted', 'success'); load(); }
    catch (err) { toast(err.message, 'error'); }
  }

  const cols = [
    { key: 'title', label: 'Title' },
    { key: 'report_type', label: 'Type', render: (v) => TYPES.find((t) => t[0] === v)?.[1] || v },
    { key: 'franchise_name', label: 'Franchise', render: (v) => v || 'Corporate' },
    { key: 'generated_by_name', label: 'Generated By' },
    { key: 'generated_at', label: 'Generated', render: fmtDateTime },
    {
      key: 'id', label: '', render: (_, row) => (
        <div style={{ display: 'flex', gap: '.4rem' }}>
          <button className="btn btn-sm btn-secondary" onClick={(e) => { e.stopPropagation(); setModal(row); }}>View</button>
          <button className="btn btn-sm btn-danger" onClick={(e) => { e.stopPropagation(); remove(row); }}>Delete</button>
        </div>
      ),
    },
  ];

  return (
    <>
      <div className="page-header"><h2>Reports</h2><p className="text-muted">Generated analytics and reports</p></div>

      <div className="toolbar">
        <div className="toolbar-left"><SearchBox value={query} onChange={(v) => { setQuery(v); setPage(1); }} placeholder="Search reports..." /></div>
        <div className="toolbar-right"><button className="btn btn-primary" onClick={openNew}>+ New Report</button></div>
      </div>

      {loading ? (
        <div className="loading-container"><div className="spinner" /></div>
      ) : (
        <>
          <DataTable cols={cols} data={slice} sortable />
          <Pagination page={page} total={total} onChange={setPage} />
        </>
      )}

      {modal === 'new' && (
        <Modal title="New Report" onClose={() => setModal(null)} onSave={create} saving={saving} saveLabel="Generate">
          <div className="form-group"><label className="form-label">Title</label><input value={form.title} onChange={(e) => setForm({ ...form, title: e.target.value })} /></div>
          <div className="form-group"><label className="form-label">Type</label>
            <select value={form.report_type} onChange={(e) => setForm({ ...form, report_type: e.target.value })}>
              {TYPES.map(([v, l]) => <option key={v} value={v}>{l}</option>)}
            </select>
          </div>
          <div className="form-group"><label className="form-label">Notes</label><textarea rows={3} value={form.notes} onChange={(e) => setForm({ ...form, notes: e.target.value })} /></div>
        </Modal>
      )}

      {modal && modal !== 'new' && (
        <Modal title={modal.title} onClose={() => setModal(null)}>
          <p><strong>Type:</strong> {TYPES.find((t) => t[0] === modal.report_type)?.[1] || modal.report_type}</p>
          <p><strong>Franchise:</strong> {modal.franchise_name || 'Corporate'}</p>
          <p><strong>Generated By:</strong> {modal.generated_by_name}</p>
          <p><strong>Generated At:</strong> {fmtDateTime(modal.generated_at)}</p>
          {modal.notes && <p><strong>Notes:</strong> {modal.notes}</p>}
          {modal.data && Object.keys(modal.data).length > 0 && (
            <>
              <label className="form-label">Data</label>
              <pre style={{ background: 'var(--surface)', padding: '.75rem', borderRadius: 8, overflow: 'auto', fontSize: '.75rem' }}>
                {JSON.stringify(modal.data, null, 2)}
              </pre>
            </>
          )}
        </Modal>
      )}
    </>
  );
}
